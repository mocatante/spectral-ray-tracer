# W: 95 x 3, 已乘 5nm
W = torch.from_numpy(W_raw * 5.0).to(device)

# XYZ -> linear sRGB (D65)
R = torch.tensor([
    [ 3.2406, -1.5372, -0.4986],
    [-0.9689,  1.8758,  0.0415],
    [ 0.0557, -0.2040,  1.0570],
], dtype=torch.float32, device=device)

# 与渲染循环一致的归一化
kNorm = 106.85

# A: 3 x 95
# 对应: 给定光谱 s (95), 返回线性 RGB (3)
A = (R @ W.T) / kNorm   # 3 x 95

# ============================================================
# 2. 参数 B (95 x 3)，用伪逆初始化
# ============================================================
B_init = torch.linalg.pinv(A)   # 95 x 3
B = torch.nn.Parameter(B_init.clone())

optimizer = torch.optim.Adam([B], lr=1e-2)
scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=20000)

# ============================================================
# 3. 训练
# ============================================================
N = 20000
BATCH = 8192

for step in range(N):
    # 采样: 一半是 [0,1] 反射率, 一半是 [0,4] 发光/HDR
    c_lo  = torch.rand(BATCH, 3, device=device)
    c_hi  = torch.rand(BATCH, 3, device=device) * 4.0
    c_all = torch.cat([c_lo, c_hi], 0)   # (2B, 3)

    # 前向: c -> s -> c_hat
    s     = c_all @ B.T         # (2B, 95)
    c_hat = s     @ A.T         # (2B, 3)

    # 1) 往返一致
    loss_rt = ((c_hat - c_all) ** 2).mean()

    # 2) 非负（反射率不能为负）
    loss_nn = torch.relu(-B).pow(2).mean()

    # 3) 有界：只对 [0,1] 反射率区间要求 s <= 1
    s_lo = c_lo @ B.T
    loss_bound = torch.relu(s_lo - 1.0).pow(2).mean()

    # 4) 平滑：二阶差分
    d2 = B[2:] - 2 * B[1:-1] + B[:-2]   # 93 x 3
    loss_smooth = d2.pow(2).mean()

    loss = loss_rt \
         + 100.0  * loss_nn \
         + 1.0    * loss_bound \
         + 0.01   * loss_smooth

    optimizer.zero_grad()
    loss.backward()
    optimizer.step()
    scheduler.step()

    if step % 1000 == 0:
        print(f"[{step:5d}] "
              f"rt={loss_rt.item():.3e}  "
              f"nn={loss_nn.item():.3e}  "
              f"bound={loss_bound.item():.3e}  "
              f"smooth={loss_smooth.item():.3e}")

