// 线性 RGB 在指定通道处的近似光谱值(按通道)
inline float rgbToSpectralAtChannel(const Color& c, int i) {
    return c.x() * kB[i][0]
        + c.y() * kB[i][1]
        + c.z() * kB[i][2];
}

// 线性 RGB 在指定通道处的近似反射率值(按通道)
inline float rgbToReflectanceAtChannel(const Color& c, int i) {
    float s = rgbToSpectralAtChannel(c, i);
    return std::clamp(s, 0.0f, 1.0f);
}

// 将波长转换为通道索引
inline int wavelengthToChannelIndex(float lambda) {
    return std::clamp(
        (int)std::lround((lambda - SpectralColor::kWavelengthMinNm)
            / SpectralColor::kWavelengthStepNm),
        0, SpectralColor::kChannelCount - 1);
}

// 线性 RGB 在指定波长处的近似光谱值(按波长)
inline float rgbToSpectralAtWavelength(const Color& c, float lambda) {
    //return linearRGBToSpectralValueAtWavelength(c, lambda);

    return rgbToSpectralAtChannel(c, wavelengthToChannelIndex(lambda));
}

