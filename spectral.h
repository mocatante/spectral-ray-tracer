// W: 95 x 3: kXYZWeights5nm
// s: 95 x 1: spectralRadiance
// x: 3 x 1: XYZ三色刺激值
// R: 3 x 3: XYZ转线性sRGB矩阵
// c: 3 x 1: 线性sRGB

// 光谱渲染原理
// x = W^T * s
// c = R * x

// 由于材质大多数是RGB定义, 需要反解光谱
// 即 c = R * W^T * s
// 记 A = R * W^T
// A 是 3 x 95 的矩阵
// c = A * s
// 预期: s = A^-1 * c 
// 实际上, A非方阵, 不能直接求逆
// 且问题本身是欠定的, 即 3 个方程, 95 个未知数, 无法唯一确定 s

// 寻找矩阵 95 x 3 的矩阵 B 
// 使得 AB = I_3
// 满足 s = B * c
// 可以验证: As = A(Bc) = (AB)c = I_3 * c = c

// 对于寻找 B, 简单粗暴, 我们根据需要建立loss训练模型

