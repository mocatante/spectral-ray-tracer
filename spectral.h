    static vec3 linearToSRGB(const vec3& linearRGB) {
        return vec3(
            encodeSRGBChannel(linearRGB.x()),
            encodeSRGBChannel(linearRGB.y()),
            encodeSRGBChannel(linearRGB.z())
        );
    }

    

