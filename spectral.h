    // 第 channelIndex 通道的中心波长，单位 nm
    static float wavelengthNm(int channelIndex) {
        return kWavelengthMinNm + channelIndex * kWavelengthStepNm;
    }

    // 累积样本到 XYZ
    static void accumulateXYZ(vec3& xyz, int channelIndex, float spectralRadiance) {
        xyz = xyz + kXYZWeights5nm[channelIndex] * spectralRadiance;
    }

    // XYZ 转 线性sRGB
    static vec3 xyzToLinearSRGB(const vec3& xyz) {
        return vec3(
            3.2406f * xyz.x() - 1.5372f * xyz.y() - 0.4986f * xyz.z(),
            -0.9689f * xyz.x() + 1.8758f * xyz.y() + 0.0415f * xyz.z(),
            0.0557f * xyz.x() - 0.2040f * xyz.y() + 1.0570f * xyz.z()
        );
    }

